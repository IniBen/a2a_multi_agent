import { Injectable, Logger } from '@nestjs/common';
import Anthropic from '@anthropic-ai/sdk';
import { Task, TaskSendParams, TaskState, Artifact, DataPart } from '../shared/a2a.types';
import {
    createTask,
    updateTaskState,
    createAgentMessage,
    createTextArtifact,
    sleep,
} from '../shared/a2a.utils';

// ================================================================
// FormatterService
//
// Receives a DataPart containing structured research, sends it to
// Claude with a formatting prompt, and streams the markdown output
// back as artifact chunks.
//
// This agent demonstrates:
//   - Consuming 'data' input mode (not plain text)
//   - Streaming token-by-token output as artifact chunks
//   - A different Claude prompt/persona from the researcher
// ================================================================

const client = new Anthropic({ apiKey: process.env.ANTHROPIC_API_KEY });

const FORMATTER_SYSTEM_PROMPT = `You are a professional crypto analyst and technical writer.

You will receive structured JSON data about a cryptocurrency and must produce a beautifully formatted markdown report.

The report MUST follow this exact structure:

# {Full Name} ({SYMBOL}) — Research Report

## Overview
A concise 2-3 sentence overview.

## Key Facts
| Field | Value |
|-------|-------|
| Category | ... |
| Consensus | ... |
| Launch Year | ... |
| Founder | ... |

## Use Case
One clear paragraph explaining what problem this coin solves.

## Key Features
- Feature one
- Feature two
- Feature three
- Feature four

## Summary
A well-written closing paragraph synthesising the above.

---
*Report generated by Crypto Formatter Agent*

Do not add any text before or after the report. Output only the markdown.`;

const taskStore = new Map<string, Task>();

@Injectable()
export class FormatterService {
    private readonly logger = new Logger(FormatterService.name);

    // ── Synchronous handler ─────────────────────────────────────────

    async handleTask(params: TaskSendParams): Promise<Task> {
        let task = createTask(params.id, 'submitted', params.sessionId);
        taskStore.set(task.id, task);

        task = updateTaskState(task, 'working', createAgentMessage('Formatting research into report...'));
        taskStore.set(task.id, task);

        const researchData = this.extractDataFromMessage(params.message);
        if (!researchData) {
            task = updateTaskState(
                task,
                'failed',
                createAgentMessage('No structured data found in message. Expected a DataPart.'),
            );
            taskStore.set(task.id, task);
            return task;
        }

        this.logger.log(`Formatting report for: ${researchData.fullName ?? 'unknown coin'}`);

        try {
            const response = await client.messages.create({
                model: 'claude-opus-4-5',
                max_tokens: 2048,
                system: FORMATTER_SYSTEM_PROMPT,
                messages: [
                    {
                        role: 'user',
                        content: `Format this research data into the markdown report:\n\n${JSON.stringify(researchData, null, 2)}`,
                    },
                ],
            });

            const markdownReport = response.content
                .filter((b) => b.type === 'text')
                .map((b: any) => b.text)
                .join('');

            task = {
                ...updateTaskState(task, 'completed'),
                artifacts: [
                    createTextArtifact(
                        'markdown-report',
                        markdownReport,
                        `Full markdown report for ${researchData.fullName ?? 'cryptocurrency'}`,
                    ),
                ],
                history: [params.message],
            };
        } catch (err) {
            this.logger.error(`Claude formatting error: ${err.message}`);
            task = updateTaskState(task, 'failed', createAgentMessage(`Formatting failed: ${err.message}`));
        }

        taskStore.set(task.id, task);
        return task;
    }

    // ── Streaming handler ───────────────────────────────────────────
    // The formatter is a great candidate for streaming because the
    // output is long markdown — users can start reading immediately
    // as each section arrives.

    async *streamTask(params: TaskSendParams): AsyncGenerator<object> {
        let task = createTask(params.id, 'submitted', params.sessionId);
        taskStore.set(task.id, task);
        yield { id: task.id, status: task.status, final: false };

        await sleep(100);
        task = updateTaskState(task, 'working', createAgentMessage('Preparing report template...'));
        taskStore.set(task.id, task);
        yield { id: task.id, status: task.status, final: false };

        const researchData = this.extractDataFromMessage(params.message);
        if (!researchData) {
            task = updateTaskState(task, 'failed', createAgentMessage('No DataPart found in message.'));
            taskStore.set(task.id, task);
            yield { id: task.id, status: task.status, final: true };
            return;
        }

        try {
            const stream = await client.messages.stream({
                model: 'claude-opus-4-5',
                max_tokens: 2048,
                system: FORMATTER_SYSTEM_PROMPT,
                messages: [
                    {
                        role: 'user',
                        content: `Format this research data into the markdown report:\n\n${JSON.stringify(researchData, null, 2)}`,
                    },
                ],
            });

            task = updateTaskState(task, 'working', createAgentMessage('Claude is writing the report...'));
            taskStore.set(task.id, task);
            yield { id: task.id, status: task.status, final: false };

            let accumulated = '';
            let chunkCount = 0;

            for await (const delta of stream) {
                if (delta.type === 'content_block_delta' && delta.delta.type === 'text_delta') {
                    accumulated += delta.delta.text;
                    chunkCount++;

                    // Stream every 5 tokens — report output is prose, so
                    // more frequent updates give a nicer typing feel
                    if (chunkCount % 5 === 0) {
                        const chunkArtifact: Artifact = {
                            name: 'markdown-report',
                            parts: [{ type: 'text', text: accumulated }],
                            index: 0,
                            append: chunkCount > 5,
                            lastChunk: false,
                        };
                        yield { id: task.id, artifact: chunkArtifact, final: false };
                    }
                }
            }

            // Final complete artifact
            const finalArtifact: Artifact = {
                name: 'markdown-report',
                description: `Formatted report for ${researchData.fullName ?? 'cryptocurrency'}`,
                parts: [{ type: 'text', text: accumulated }],
                index: 0,
                lastChunk: true,
            };
            yield { id: task.id, artifact: finalArtifact, final: false };

            task = {
                ...updateTaskState(task, 'completed'),
                artifacts: [finalArtifact],
                history: [params.message],
            };
            taskStore.set(task.id, task);
            yield { id: task.id, status: task.status, final: true };
        } catch (err) {
            this.logger.error(`Claude streaming formatter error: ${err.message}`);
            task = updateTaskState(task, 'failed', createAgentMessage(err.message));
            taskStore.set(task.id, task);
            yield { id: task.id, status: task.status, final: true };
        }
    }

    // ── Other operations ────────────────────────────────────────────

    getTask(id: string): Task | undefined {
        return taskStore.get(id);
    }

    cancelTask(id: string): Task | undefined {
        const task = taskStore.get(id);
        if (!task) return undefined;
        const cancelable: TaskState[] = ['submitted', 'working', 'input-required'];
        if (!cancelable.includes(task.status.state)) return undefined;
        const cancelled = updateTaskState(task, 'cancelled');
        taskStore.set(id, cancelled);
        return cancelled;
    }

    // ── Private helpers ─────────────────────────────────────────────

    private extractDataFromMessage(message: any): Record<string, any> | null {
        // Look for a DataPart in the message parts
        for (const part of message.parts ?? []) {
            if (part.type === 'data' && part.data) {
                return part.data;
            }
        }
        // Fallback: try to parse a TextPart as JSON (orchestrator may
        // have serialised the data object as a text string)
        for (const part of message.parts ?? []) {
            if (part.type === 'text') {
                try {
                    return JSON.parse(part.text);
                } catch {
                    // not JSON, skip
                }
            }
        }
        return null;
    }
}